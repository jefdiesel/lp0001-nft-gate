# LP-0001 performance harness for REQUIREMENTS-MAP rows 31 and 32.
#
# WRITE-ONLY ARTIFACT. This agent never ran it: a real proof is the owner's call.
# See docs/lp0001/PERFORMANCE-BENCH.md for the exact run procedure and guards.
#
# What it does when the owner runs it:
#   1. Times one real proof generation (the guarded 91-real-proof.sh path) and
#      records wall seconds plus the peak footprint already sampled there.
#   2. Reads the on-chain Act gas recorded by T08-consumer.sh and puts both
#      figures into tests/onchain/bench-results.csv and
#      docs/lp0001/BENCHMARK-RESULTS.md.
# It never deploys, proves, pushes, or touches another repo.

set -eu

BENCH_OWNER_OK=${BENCH_OWNER_OK:-0}
if [ "$BENCH_OWNER_OK" != 1 ]; then
  echo "STOP: set BENCH_OWNER_OK=1 only after the owner has authorised a real proof and T08." >&2
  exit 2
fi

# Same build host and rules as the other on-chain tests.
# BENCH_ENV lets the offline self-test point at a stub env (it sets only G).
. "${BENCH_ENV:-$(dirname "$0")/env.sh}"

OUT=$G/run/bench
mkdir -p "$OUT"
CSV=${BENCH_CSV:-$(cd "$(dirname "$0")" && pwd)/bench-results.csv}
MD=${BENCH_MD:-$(cd "$(dirname "$0")/../.." && pwd)/docs/lp0001/BENCHMARK-RESULTS.md}

# No external prover under any circumstances (AGENTS.md §Rules).
if command -v r0vm >/dev/null 2>&1; then
  echo "STOP: r0vm is on PATH" >&2
  exit 3
fi

note() { echo "$(date -u +%FT%TZ) $*" | tee -a "$OUT/log.txt"; }

# --- 31: proof generation time ------------------------------------------------
# The proof itself is still started only by the guarded 91-real-proof.sh, which
# uses RISC0_PROVER=local, RAYON_NUM_THREADS=4 and its own memory watchdog.
PROOF_LOG=$(ls -1dt "$G"/run/real-proof-* 2>/dev/null | head -1 || true)
if [ -z "$PROOF_LOG" ] || [ ! -f "$PROOF_LOG/time.log" ]; then
  echo "STOP: no guarded real-proof log found; run 90-build-cli-prove.sh then 91-real-proof.sh first." >&2
  echo "This harness does not start a proof by itself." >&2
  exit 4
fi

# macOS /usr/bin/time -l prints "   12.34 real   5.67 user …": the number comes before "real".
PROOF_SECS=$(awk '/real/{for(i=1;i<=NF;i++) if ($i=="real") {print $(i-1); exit}}' "$PROOF_LOG/time.log" || true)
PEAK_KB=$(grep footprint_kb "$PROOF_LOG/sampler.log" 2>/dev/null | sort -t= -k2 -n | tail -1 | sed -E 's/.*footprint_kb=([0-9]+).*/\1/' || true)
MACHINE=$(sysctl -n machdep.cpu.brand_string 2>/dev/null || uname -m)
MEM_GIB=$(( $(sysctl -n hw.memsize 2>/dev/null || echo 0) / 1073741824 ))
OS=$(sw_vers -productVersion 2>/dev/null || uname -s)

# --- 32: on-chain verification gas/CU -----------------------------------------
# T08-consumer.sh sources lib.sh T08 (TNAME=T08), so its log is run/T08/log.txt and
# finish_test writes "T08 PASS…"; it records "Act gas: fee <n>" from decode-tx.
# On the public rc3 chain the Act comes from rc3/E2E-rc3.sh instead (BENCH_T08_LOG=$G/run/E2E/log.txt,
# BENCH_T08_NAME=E2E); its "Act gas: fee <n>" is what the payer was charged.
T08_LOG=${BENCH_T08_LOG:-$G/run/T08/log.txt}
T08_NAME=${BENCH_T08_NAME:-T08}
ACT_GAS=$(grep -oE 'Act gas: fee [0-9]+' "$T08_LOG" 2>/dev/null | tail -1 | awk '{print $4}' || true)
T08_VERDICT=$(grep -oE "^$T08_NAME (PASS|FAIL|BLOCKED)" "$T08_LOG" 2>/dev/null | tail -1 | awk '{print $2}' || true)

# --- results ------------------------------------------------------------------
if [ ! -f "$CSV" ]; then
  printf 'timestamp,row,metric,value,unit,source,notes\n' > "$CSV"
fi
TS=$(date -u +%FT%TZ)
if [ -n "$PROOF_SECS" ]; then
  printf '%s,31,proof_wall_time,%s,s,%s,"%s; %s GiB; macOS %s"\n' \
    "$TS" "$PROOF_SECS" "$PROOF_LOG/time.log" "$MACHINE" "$MEM_GIB" "$OS" >> "$CSV"
fi
if [ -n "$PEAK_KB" ]; then
  printf '%s,31,proof_peak_footprint,%s,KiB,%s,\n' "$TS" "$PEAK_KB" "$PROOF_LOG/sampler.log" >> "$CSV"
fi
if [ -n "$ACT_GAS" ]; then
  printf '%s,32,act_gas,%s,fee-units,%s,"T08 verdict: %s"\n' \
    "$TS" "$ACT_GAS" "$T08_LOG" "${T08_VERDICT:-unknown}" >> "$CSV"
fi

{
  echo "# LP-0001 measured performance"
  echo
  echo "Generated by \`tests/onchain/BENCH-proof-and-gas.sh\` on $TS."
  echo "No numbers are committed until the owner runs the harness on the build host."
  echo
  echo "| Row | Metric | Value | Source |"
  echo "| --- | --- | --- | --- |"
  echo "| 31 | Proof generation wall time | ${PROOF_SECS:-not measured} s | ${PROOF_LOG:-none}/time.log |"
  echo "| 31 | Peak proof footprint | ${PEAK_KB:-not measured} KiB | ${PROOF_LOG:-none}/sampler.log |"
  echo "| 32 | On-chain Act gas | ${ACT_GAS:-not measured} fee units | ${T08_LOG} |"
  echo "| 32 | T08 verdict | ${T08_VERDICT:-not run} | ${T08_LOG} |"
  echo
  echo "Machine: ${MACHINE}, ${MEM_GIB} GiB, macOS ${OS}."
} > "$MD"

note "bench written: proof=${PROOF_SECS:-none}s peak=${PEAK_KB:-none}KiB act_gas=${ACT_GAS:-none}"
echo "results: $CSV and $MD"
